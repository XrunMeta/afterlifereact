"""remember_me_intent.py — "나를 기억해" 류 발화를 감지해 Remember Me 시트를 여는 신호.

이 모듈이 하는 일은 **UI 를 열라는 bool 하나**를 만드는 것이다. 이름은 뽑지 않는다.
반환 타입이 bool 인 것 자체가 계약이다 — 이름이 실려 나갈 통로를 두지 않는다.

T-467 B 를 제거하면서 이 모듈은 남기는 이유:
  T-467 B 는 "응/그래" 를 듣고 **이름을 확정**했다. STT 오인식이 그대로 신원이 되어
  person 43 의 L2' 에 "이름이 카메라이다" 가 8건 쌓였고("내일은 기억하니?" 가 이름
  "카메라" 로 확정된 것), persons 44 는 display_name 이 "나는" 이 됐다.
  여기서는 잘못 발동해도 시트가 한 번 열릴 뿐이고, 이름은 사용자가 직접 입력한다.
  같은 정규식이라도 **결과를 어디에 쓰느냐**가 다르다.

음성은 유도, 수신은 UI — 이 구분을 깨지 않는 선에서만 음성을 읽는다.
"""
from __future__ import annotations

import re

# 대상이 말하는 사람 자신일 때만 발동한다. "그 얘기 기억해줘" 로 시트가 뜨면
# 대화가 불가능해진다.
#
# AFL-926 (2026-10-02 실통화): 예전엔 내가·제가 같은 **주어형**도 대상으로 받고 동사까지
# 10자를 허용해서 "아침에 내가 뭐 했는지 너 기억해" 가 걸렸다(시트가 열리고 마이크가 닫혀
# 턴이 돌아오지 않았다). 주어형은 '내가 한 일' 을 가리킨다 — 대상이 아니다. 그래서 둘로 나눈다:
#   이름형 — "내 이름은 지호야 기억해줘": 이름이 끼므로 10자 간격 허용.
#   목적어형 — "나 기억해", "날 꼭 기억해", "저를 기억해주세요": 바로 뒤에 동사(부사만 허용).
_ACT = r"(?:기억|저장|등록)\s*(?:해|하)"
_NAME_TRIGGER = re.compile(rf"(?:(?:내|제)\s*)?이름[^.!?\n]{{0,10}}?{_ACT}")
_ME_TRIGGER = re.compile(rf"(?:^|[\s,])(?:나를|날|저를|나|저)\s*(?:(?:좀|꼭|제발)\s*)*{_ACT}")

# 의문형 배제. 물음표 또는 의문 어미로 끝나면 요청이 아니라 질문이다.
_QUESTION = re.compile(r"(?:\?|니|냐|나요|까요|어요|아요|해요)\s*[?！!]?\s*$")


def wants_remember_me(text: object) -> bool:
    """Remember Me 시트를 열어야 하는 발화면 True.

    비문자열·빈 문자열은 조용히 False — 이 경로는 통화 중 매 발화마다 호출되므로
    입력이 이상하다고 예외를 던지면 통화가 끊긴다.
    """
    if not isinstance(text, str):
        return False
    s = text.strip()
    if not s:
        return False
    if _QUESTION.search(s):
        return False
    return bool(_NAME_TRIGGER.search(s) or _ME_TRIGGER.search(s))
