def get_dialect_traits(region: str | None) -> str | None:
    """지역명 (예: '경상도') 으로 방언 카탈로그 조회. 미상은 None."""
    if not region:
        return None
    key = str(region).strip()
    return DIALECT_TRAITS.get(key)
